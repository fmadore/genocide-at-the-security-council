/** Rasterise captioned SVG markup. `scale` of 2 gives a usable print density. */
export async function svgToPng(svg: string, width: number, height: number, scale = 2) {
	const blob = new Blob([svg], { type: 'image/svg+xml;charset=utf-8' });
	const url = URL.createObjectURL(blob);
	try {
		const image = new Image();
		image.width = width;
		image.height = height;
		await new Promise<void>((resolve, reject) => {
			image.onload = () => resolve();
			image.onerror = () => reject(new Error('The figure could not be rasterised.'));
			image.src = url;
		});
		const canvas = document.createElement('canvas');
		canvas.width = Math.round(width * scale);
		canvas.height = Math.round(height * scale);
		const context = canvas.getContext('2d');
		if (!context) throw new Error('This browser gave no 2D canvas context.');
		context.scale(scale, scale);
		context.drawImage(image, 0, 0, width, height);
		return await new Promise<Blob>((resolve, reject) => {
			canvas.toBlob(
				(result) => (result ? resolve(result) : reject(new Error('The PNG was empty.'))),
				'image/png'
			);
		});
	} finally {
		URL.revokeObjectURL(url);
	}
}

/**
 * Save a blob under a name.
 *
 * The anchor is put in the document before it is clicked and the object URL is
 * revoked on the next frame rather than immediately: a detached anchor does not
 * reliably trigger a download outside Chromium, and revoking synchronously can
 * beat the browser to reading the blob.
 */
export function save(blob: Blob, name: string): void {
	const url = URL.createObjectURL(blob);
	const anchor = document.createElement('a');
	anchor.href = url;
	anchor.download = name;
	anchor.style.display = 'none';
	document.body.append(anchor);
	anchor.click();
	anchor.remove();
	setTimeout(() => URL.revokeObjectURL(url), 0);
}

/** Save a built CSV. The BOM is what makes Excel read UTF-8 as UTF-8. */
export function saveCsv(csv: string, name: string): void {
	save(new Blob(['﻿', csv], { type: 'text/csv;charset=utf-8' }), name);
}
